"""Run every ground-truth SQL once against the live DB and write
`docs/task1_ground_truth.md` (Task 1 deliverable: question + SQL + result).

Also writes `benchmark/ground_truth_results.json` for later reuse by the
evaluation runner (it compares agent-generated rows against these).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sqlalchemy import create_engine, text  # noqa: E402

from app.config import DATABASE_URL  # noqa: E402

GT_PATH = ROOT / "benchmark" / "ground_truth.json"
RESULTS_PATH = ROOT / "benchmark" / "ground_truth_results.json"
DOC_PATH = ROOT / "docs" / "task1_ground_truth.md"

MAX_PREVIEW_ROWS = 5  # shown inline in the markdown


def normalize_cell(v):
    if v is None:
        return None
    if hasattr(v, "isoformat"):
        return v.isoformat()
    # Decimal / Numeric -> float for JSON
    try:
        from decimal import Decimal

        if isinstance(v, Decimal):
            return float(v)
    except Exception:
        pass
    return v


def run_one(engine, sql: str) -> dict:
    with engine.connect() as conn:
        result = conn.execute(text(sql))
        columns = list(result.keys())
        rows = [list(map(normalize_cell, r)) for r in result.fetchall()]
    return {"columns": columns, "rowcount": len(rows), "rows": rows}


def render_md_table(columns: list[str], rows: list[list], limit: int) -> str:
    if not rows:
        return "_(no rows returned)_"
    head = "| " + " | ".join(columns) + " |"
    sep = "| " + " | ".join("---" for _ in columns) + " |"
    body = []
    for r in rows[:limit]:
        body.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    note = ""
    if len(rows) > limit:
        note = f"\n\n_(showing {limit} of {len(rows)} rows)_"
    return "\n".join([head, sep, *body]) + note


def main():
    gt = json.loads(GT_PATH.read_text(encoding="utf-8"))
    engine = create_engine(DATABASE_URL, pool_pre_ping=True)

    results = []
    md_parts = [
        "# Task 1: Ground-Truth SQL & Verified Results",
        "",
        "_Auto-generated by `benchmark/build_task1_doc.py` — every query below was "
        "executed against the live `classicmodels` PostgreSQL database and the "
        "rendered table is the actual output._",
        "",
        f"**Total questions:** {len(gt)}    "
        f"**Database:** `classicmodels` (Postgres 16, port 5433)",
        "",
        "---",
        "",
    ]

    for item in gt:
        qid, question, sql = item["id"], item["question"], item["sql"]
        out = run_one(engine, sql)
        results.append(
            {"id": qid, "question": question, "sql": sql, **out}
        )
        md_parts.append(f"## Q{qid:02d} — {question}")
        md_parts.append("")
        md_parts.append("```sql")
        md_parts.append(sql)
        md_parts.append("```")
        md_parts.append("")
        md_parts.append(f"**Rows returned:** {out['rowcount']}")
        md_parts.append("")
        md_parts.append(render_md_table(out["columns"], out["rows"], MAX_PREVIEW_ROWS))
        md_parts.append("")
        md_parts.append("---")
        md_parts.append("")

    RESULTS_PATH.write_text(json.dumps(results, indent=2), encoding="utf-8")
    DOC_PATH.write_text("\n".join(md_parts), encoding="utf-8")
    print(f"Wrote {RESULTS_PATH}")
    print(f"Wrote {DOC_PATH}")
    print(f"Executed {len(gt)} ground-truth queries successfully.")


if __name__ == "__main__":
    main()
